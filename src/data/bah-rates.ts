// Prefer a ZIP's own direct RAW entry; only fall back to the alias table
// (or the ZIP itself) when there is no direct entry.
function resolveZip(mhaZip: string): string {
  if (mhaZip in RAW) return mhaZip;
  if (mhaZip in ZIP_ALIAS) return ZIP_ALIAS[mhaZip];
  // Any other ZIP DoD lists: its own MHA row, or its county cost group (ZZ###) row.
  return bahKeyForZip(mhaZip) ?? mhaZip;
}

export function getBahRate(
  mhaZip: string,
  grade: PayGrade,
  withDependents: boolean,
): number | null {
  const mha = RAW[resolveZip(mhaZip)];
  if (!mha) return null;
  const pair = mha[GRADE_INDEX[grade]];
  return withDependents ? pair[0] : pair[1];
}

export function hasBahData(mhaZip: string): boolean {
  return resolveZip(mhaZip) in RAW;
}

export interface BahLookupResult {
  rate: number;
  exact: boolean;
}

/**
 * Find E5-with-dep BAH for any US ZIP code.
 * Falls back through alias → 3-digit prefix → 2-digit prefix → 1-digit prefix
 * so arbitrary college/school ZIP codes always return a nearest-MHA estimate.
 */
/**
 * The MHA key in the BAH table to use for an arbitrary ZIP: the ZIP's own MHA
 * (exact or alias) if there is one, otherwise the table key sharing the longest
 * ZIP prefix (3, then 2, then 1 digit) and, among those, the numerically
 * CLOSEST one. (It used to take the first key in table order, which is
 * arbitrary: ZIP 90210 could land on an unrelated area of the same prefix.)
 */
export function findBahKeyApprox(zip: string): { key: string; exact: boolean } | null {
  const resolved = resolveZip(zip);
  // Keep the caller's ZIP as the key (rows for county cost groups are keyed ZZ###, which is not a ZIP);
  // getBahRate/findBahRateApprox resolve it back to the row.
  if (resolved in RAW) return { key: zip, exact: true };

  const allZips = Object.keys(RAW);
  const target = Number(zip);
  for (const len of [3, 2, 1]) {
    const pre = zip.slice(0, len);
    let best: string | null = null;
    let bestDist = Infinity;
    for (const z of allZips) {
      if (!z.startsWith(pre)) continue;
      const d = Math.abs(Number(z) - target);
      if (d < bestDist) { best = z; bestDist = d; }
    }
    if (best) return { key: best, exact: false };
  }
  return null;
}

export function findBahRateApprox(
  zip: string,
  grade: PayGrade,
  withDependents: boolean,
): BahLookupResult | null {
  const match = findBahKeyApprox(zip);
  if (!match) return null;
  const pair = RAW[resolveZip(match.key)][GRADE_INDEX[grade]];
  return { rate: withDependents ? pair[0] : pair[1], exact: match.exact };
}
