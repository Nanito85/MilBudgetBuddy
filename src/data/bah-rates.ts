export function getBahRate(
  mhaZip: string,
  grade: PayGrade,
  withDependents: boolean,
): number | null {
  const mha = RAW[mhaZip];
  if (!mha) return null;
  const pair = mha[GRADE_INDEX[grade]];
  return withDependents ? pair[0] : pair[1];
}

export function hasBahData(mhaZip: string): boolean {
  return mhaZip in RAW;
}
