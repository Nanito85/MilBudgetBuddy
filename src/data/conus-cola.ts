/** Returns the base-rate array index for the highest YOS bracket <= memberYOS. */
function bracketIndex(yos: number): number {
  let idx = 0;
  for (let i = 0; i < CONUS_COLA_YOS_BRACKETS.length; i++) {
    if (yos >= CONUS_COLA_YOS_BRACKETS[i]) idx = i;
    else break;
  }
  return idx;
}

